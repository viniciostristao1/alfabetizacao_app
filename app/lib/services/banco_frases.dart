/// Banco de frases do **Modo Frases**: cada [Palavra] do [bancoPalavras] vira
/// UMA frase curta e criativa (ex.: `leão` → `O leão mora na savana`).
///
/// Como ler: a chave é [chaveFrase] —
/// `categoria|texto|tema|habitat|regiao` — porque o mesmo texto aparece em
/// lugares diferentes com frase diferente (ex.: `banana` sem tema e `banana`
/// do `pomar`; `quadro` do `museu` e da `escola`). Frases em forma normal com
/// acentos; a caixa (MAIÚSCULAS/minúsculas) é aplicada na hora com o
/// `ModoLeitura` da tela de estudo. Palavras fora do banco (ex.: categoria
/// `Escrever`, digitadas na hora) não têm frase — [fraseDe] retorna null e a
/// tela mostra a palavra pura.
///
/// Um teste (`test/banco_frases_test.dart`) garante: toda palavra do banco tem
/// frase, sem frase vazia, sem duplicata e com a palavra-alvo dentro.
String chaveFrase(Palavra p) =>
    '${p.categoria.name}|${p.texto}|${p.tema ?? ''}|${p.habitat ?? ''}|${p.regiao ?? ''}';

/// A frase da palavra (forma normal, com acentos) ou null se não houver.
String? fraseDe(Palavra p) => kFrases[chaveFrase(p)];

/// A frase da palavra ou, sem frase, a própria palavra.
String fraseOuPalavra(Palavra p) => fraseDe(p) ?? p.texto;

